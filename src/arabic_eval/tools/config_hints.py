_INDEX_RE = re.compile(r"\.\d+(?=\.|$)")
_PHASE_RE = re.compile(r"^training\.phases\.(embedding_alignment|warmup|sft)")


def norm_path(path: str) -> str:
    """The hint key of a concrete config path: list indexes → ``*``, phase names → ``*``
    (the same rule as ``normPath`` in the page)."""
    return _PHASE_RE.sub("training.phases.*", _INDEX_RE.sub(".*", path))


def hint_for(path: str) -> Optional[Tuple[str, str]]:
    """The ``(meaning, example)`` of a concrete path, or ``None``."""
    n = norm_path(path)
    return FIELD_HINTS.get(n) or FIELD_HINTS.get(n.rsplit(".", 1)[-1])
